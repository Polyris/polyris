"""Parity test: notify_asset_subscribers._flatten_asset_names correctly extracts
asset names from the DDB metadata format used by wait_for storage.

Principle #28: functions that traverse wait_for JSON structures need a parity
test to verify correctness.

Serialization note: two wait_for formats exist in the system:
  - SFN input format (key `asset_name`): used by check_assets, generated by
    _serialize_wait_for in generators.py
  - DDB metadata format (key `name`): stored in pipeline-tokens.wait_for and
    read by notify_asset_subscribers, generated by _serialize_wait_for_metadata

_flatten_asset_names operates on the DDB metadata format. Cross-comparing with
check_assets._evaluate_wait_for (SFN format) would be a false equivalence test —
those functions consume different schemas.
"""

import importlib
import importlib.util
import sys
from pathlib import Path

import pytest

NOTIFY_DIR = Path(__file__).parent.parent.parent / "sam/lambdas/notify_asset_subscribers"


def _load_flatten():
    """Load _flatten_asset_names in isolation (see test_wait_for_or_sibling_cleanup.py)."""
    spec_dal = importlib.util.spec_from_file_location("_notify_dal_parity", NOTIFY_DIR / "dal/__init__.py")
    dal = importlib.util.module_from_spec(spec_dal)
    spec_dal.loader.exec_module(dal)

    old_dal = sys.modules.get("dal")
    sys.modules["dal"] = dal
    try:
        spec = importlib.util.spec_from_file_location("_notify_index_parity", NOTIFY_DIR / "index.py")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    finally:
        if old_dal is None:
            sys.modules.pop("dal", None)
        else:
            sys.modules["dal"] = old_dal
    return mod._flatten_asset_names


_SPECS = [
    # Simple AND list
    ([{'name': 'asset_a'}, {'name': 'asset_b'}], {'asset_a', 'asset_b'}),
    # Pure OR group
    ([{'operator': 'OR', 'assets': [{'name': 'asset_a'}, {'name': 'asset_b'}]}], {'asset_a', 'asset_b'}),
    # Mixed: plain AND member + OR group
    ([{'name': 'asset_x'}, {'operator': 'OR', 'assets': [{'name': 'asset_a'}, {'name': 'asset_b'}]}],
     {'asset_x', 'asset_a', 'asset_b'}),
    # Single asset
    ([{'name': 'only_asset'}], {'only_asset'}),
    # Empty
    ([], set()),
]


@pytest.mark.parametrize("wait_for,expected", _SPECS)
def test_flatten_matches_expected(wait_for, expected):
    """_flatten_asset_names returns the correct set for each DDB metadata format fixture."""
    flatten = _load_flatten()
    assert flatten(wait_for) == expected
