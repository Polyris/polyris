// Emits src/ee-active.generated.ts by composing the proprietary tier surfaces
// present under src/ee/. The free<->paid seam is physical (ADR #99): when src/ee/
// is stripped (OSS build) no tier is found and an empty stub is emitted. The
// team<->enterprise boundary is a runtime entitlement (ADR #100), so every tier
// that is present is merged into one surface here and gated at runtime via can().
//
// A new tier is picked up automatically — add src/ee/<tier>/index.ts exporting a
// `surface` object; no edit here is needed. Tiers fill disjoint slots, so the
// merge order is irrelevant (sorted only for deterministic output).
//
// Runs in prebuild/predev/pretypecheck.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';

const EE = 'src/ee';
const tiers = existsSync(EE)
  ? readdirSync(EE).filter((d) => existsSync(`${EE}/${d}/index.ts`)).sort()
  : [];

const HEADER = '// AUTO-GENERATED by scripts/gen-ee-active.mjs. Do not edit.\n';

let body;
if (tiers.length === 0) {
  // OSS build: src/ee/ stripped -> empty surface, free code renders fallbacks.
  body =
    HEADER +
    '// src/ee absent (OSS build) -> empty stub.\n' +
    "import type { PaidSurface } from './ee-contract';\n" +
    'export const paidSurface: PaidSurface = {};\n';
} else {
  const imports = tiers
    .map((t, i) => `import { surface as s${i} } from './ee/${t}';`)
    .join('\n');
  const spread = tiers.map((_, i) => `...s${i}`).join(', ');
  body =
    HEADER +
    `// tiers present: ${tiers.join(', ')} -> merged surface (disjoint slots).\n` +
    "import type { PaidSurface } from './ee-contract';\n" +
    imports +
    '\n' +
    `export const paidSurface: PaidSurface = { ${spread} };\n`;
}

writeFileSync('src/ee-active.generated.ts', body);
console.log(
  `[gen-ee-active] tiers: [${tiers.join(', ')}] -> ${tiers.length ? 'merged surface' : 'stub'}`,
);
