"""Emit ``polyris/coordination`` into the runtimes that evaluate readiness.

ADR #130 §10: the coordination Lambda and console_api must run the same
readiness code as the SDK, from the same release. They cannot import the
``polyris`` package for it (the Lambda does not ship it; console_api pins a
released SDK version), so this generator copies the package into each of
them as ``coordination_core``:

* every module of ``polyris/coordination`` except ``statuses.py``, verbatim
  apart from ``from ..partitions import`` becoming ``from .partitions import``;
* ``polyris/partitions.py`` as ``partitions.py``;
* ``statuses.py`` as literal frozensets computed from ``polyris.constants``.

Run:
    python -m polyris.codegen.sync_coordination          # write
    python -m polyris.codegen.sync_coordination --check  # CI: exit 1 on drift
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_DIR = REPO_ROOT / "polyris" / "coordination"
PARTITIONS_FILE = REPO_ROOT / "polyris" / "partitions.py"
PACKAGE = "coordination_core"
TARGET_DIRS = [
    REPO_ROOT / "sam" / "lambdas" / "coordination" / PACKAGE,
    REPO_ROOT / "sam" / "lambdas" / "console_api" / PACKAGE,
]

#: Names copied from polyris/coordination/statuses.py into the literal module.
STATUS_SETS = ("RECONCILABLE", "TERMINAL", "SUCCESS_ONLY", "FAILURE", "WARNING_KINDS")
STATUS_NAMES = ("SKIPPED", "WAITING", "WAITING_PAUSED", "ABORTED", "FAILED")

_PARENT_PARTITIONS = "from ..partitions import"
# Any import that would reach outside the copied package.
_FORBIDDEN = re.compile(r"^\s*(from\s+\.\.|from\s+polyris\b|import\s+polyris\b)", re.MULTILINE)


def _header(source: str) -> str:
    return (
        f"# GENERATED by `python -m polyris.codegen.sync_coordination` from {source}.\n"
        "# Do not edit: change the source and regenerate.\n"
    )


def _render_statuses() -> str:
    from polyris.coordination import statuses

    lines = [
        '"""Task status sets used by the coordination logic (literal copy, ADR #130)."""',
        "",
    ]
    for name in STATUS_SETS:
        values = ", ".join(repr(v) for v in sorted(getattr(statuses, name)))
        lines.append(f"{name} = frozenset({{{values}}})")
    for name in STATUS_NAMES:
        lines.append(f"{name} = {getattr(statuses, name)!r}")
    return "\n".join(lines) + "\n"


def render(source_dir: Path = SOURCE_DIR, partitions_file: Path = PARTITIONS_FILE) -> Dict[str, str]:
    """Return ``{file name: content}`` for one copy of the package."""
    files: Dict[str, str] = {}
    for path in sorted(source_dir.glob("*.py")):
        if path.name == "statuses.py":
            continue
        text = path.read_text(encoding="utf-8").replace(_PARENT_PARTITIONS, "from .partitions import")
        leak = _FORBIDDEN.search(text)
        if leak:
            raise ValueError(
                f"{path.name} imports outside polyris/coordination ({leak.group(0).strip()!r}); "
                "only `from ..partitions import` can be rewritten for the copy"
            )
        files[path.name] = _header(f"polyris/coordination/{path.name}") + text
    files["statuses.py"] = _header("polyris/coordination/statuses.py") + _render_statuses()
    files["partitions.py"] = _header("polyris/partitions.py") + partitions_file.read_text(encoding="utf-8")
    return files


def sync(targets: Sequence[Path] = TARGET_DIRS, *, write: bool) -> List[Path]:
    """Compare (and with ``write`` update) every target; return the paths that differ.

    A ``.py`` file in a target that the package no longer has counts as a
    difference too, and is deleted on write.
    """
    files = render()
    changed: List[Path] = []
    for target in targets:
        for name, content in files.items():
            path = target / name
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                changed.append(path)
                if write:
                    target.mkdir(parents=True, exist_ok=True)
                    path.write_text(content, encoding="utf-8")
        if target.exists():
            for stale in sorted(target.glob("*.py")):
                if stale.name not in files:
                    changed.append(stale)
                    if write:
                        stale.unlink()
    return changed


def _display(path: Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Exit 1 if the generated copies would change; don't write.")
    args = parser.parse_args(argv)

    changed = sync(TARGET_DIRS, write=not args.check)
    if args.check:
        if changed:
            sys.stderr.write("❌ Generated coordination copies are out of sync with polyris/coordination:\n")
            for path in changed:
                sys.stderr.write(f"   {_display(path)}\n")
            sys.stderr.write("Run: python -m polyris.codegen.sync_coordination\n")
            return 1
        print("✅ Generated coordination copies in sync")
        return 0
    if changed:
        print(f"✅ Wrote {len(changed)} file(s):")
        for path in changed:
            print(f"   {_display(path)}")
    else:
        print("✅ Already in sync, no changes written")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    sys.exit(main())
