def init_pipeline(name: str, schedule: str = "@daily", base_dir: str = ".", deploy_method: str = "cfn"):
    """Create a new pipeline scaffold."""

    pipeline_dir = Path(base_dir) / name
    name_under = name.replace("-", "_")

    if pipeline_dir.exists():
        print(f"❌ Directory already exists: {pipeline_dir}")
        sys.exit(1)

    pipeline_dir.mkdir(parents=True)

    fmt = dict(name=name, name_under=name_under, schedule=schedule)

    if deploy_method == "local":
        (pipeline_dir / "dag.py").write_text(LOCAL_PIPELINE.format(**fmt))

        print(f"""
✅ Pipeline created: {pipeline_dir}/

Files:
  {pipeline_dir}/dag.py    — Pipeline definition (no AWS needed!)

Try it now:
  cd {pipeline_dir}
  polyris-validate              # Validate pipeline
  polyris-validate -v           # Verbose output
  polyris-output --json         # Full Step Functions JSON
  polyris-output --mermaid      # Generate diagram
  polyris-output --graph        # Show DAG as ASCII graph

Ready to deploy? Re-run without --local to scaffold a deployable pipeline:
  polyris-init {name}
""")
    else:
        # deploy_method == "cfn" (the default per the CLI's own --help/epilog:
        # "polyris-init my-pipeline # Create a pipeline (default)"). This
        # branch previously did not exist at all: the directory was created,
        # zero files were written, and nothing was printed — the tool's own
        # documented default invocation silently did nothing.
        (pipeline_dir / "dag.py").write_text(CFN_PIPELINE.format(**fmt))

        print(f"""
✅ Pipeline created: {pipeline_dir}/

Files:
  {pipeline_dir}/dag.py    — Pipeline definition

Try it now:
  cd {pipeline_dir}
  polyris-validate              # Validate pipeline
  polyris-validate -v           # Verbose output

Deploy:
  polyris-deploy --stage dev
""")


SCHEDULES = {
    "1": ("@daily", "Once per day (midnight UTC)"),
    "2": ("@hourly", "Once per hour"),
    "3": ("@weekly", "Once per week (Sunday midnight)"),
    "4": ("0 9 * * MON-FRI", "Weekdays at 9 AM UTC"),
    "5": ("None", "Manual only (no schedule)"),
}

DEPLOY_METHODS = {
    "1": ("local", "Try locally without AWS (explore DSL)"),
    "2": ("cfn", "CloudFormation — deploy via polyris-deploy"),
}


def _ask(prompt, default=None):
    """Ask user for input with optional default."""
    if default:
        result = input(f"  {prompt} [{default}]: ").strip()
        return result or default
    return input(f"  {prompt}: ").strip()


def _ask_choice(prompt, choices):
    """Ask user to pick from numbered choices."""
    print(f"\n  {prompt}")
    for key, (_, desc) in choices.items():
        print(f"    {key}) {desc}")
    while True:
        choice = input("  Choice [1]: ").strip() or "1"
        if choice in choices:
            return choices[choice][0]
        print(f"  Invalid choice. Pick {', '.join(choices.keys())}.")


def _build_custom_pipeline(name, schedule, tasks, deploy_method, use_remote_state=False):
    """Generate pipeline code from interactive wizard inputs."""
    
    # Build task definitions
    task_defs = []
    task_calls = []
    for t in tasks:
        params = [f'arn="arn:aws:states:us-east-1:123456789012:stateMachine:{name}-{t["name"]}"']
        if t.get("retries"):
            params.append(f'retries={t["retries"]}')
        if t.get("trigger_rule") and t["trigger_rule"] != "all_success":
            params.append(f'trigger_rule="{t["trigger_rule"]}"')
        
        params_str = ", ".join(params)
        func_name = t["name"].replace("-", "_")
        desc = t.get("description", f'{t["name"].replace("-", " ").title()} step.')
        
        task_defs.append(f'''    @task.sfn({params_str})
    def {func_name}():
        """{desc}"""
        pass''')
        task_calls.append(f"    {func_name}()")

    # Build dependency chains
    dep_lines = []
    for i, t in enumerate(tasks):
        if t.get("depends_on"):
            for dep_name in t["depends_on"]:
                dep_func = dep_name.replace("-", "_")
                task_func = t["name"].replace("-", "_")
                dep_lines.append(f"    {dep_func}() >> {task_func}()")
    
    # If no explicit deps, chain sequentially
    if not dep_lines and len(tasks) > 1:
        chain = " >> ".join(t["name"].replace("-", "_") + "()" for t in tasks)
        dep_lines = [f"    {chain}"]

    schedule_str = f'"{schedule}"' if schedule != "None" else "None"
    
    if deploy_method == "local":
        header = f'''"""
{name} pipeline.

Generated by: polyris init -i --local

Commands (run from this directory):
    polyris-validate              # Validate pipeline
    polyris-validate -v           # Verbose validation
    polyris-output --json         # Generate ASL JSON
    polyris-output --mermaid      # Generate Mermaid diagram
    polyris-output --graph        # Show DAG as ASCII graph

When ready to deploy:
    polyris-deploy --stage dev
"""
from polyris import DAG, task'''
        footer = '''
# Deploy: polyris-deploy --stage dev'''
    else:
        if use_remote_state:
            header = f'''"""
{name} pipeline.

Generated by: polyris init -i
"""
import os
from polyris import DAG, task

STAGE = os.environ.get("POLYRIS_STAGE", "dev")'''
            footer = '''
# Deploy: polyris-deploy --stage $STAGE'''
        else:
            header = f'''"""
{name} pipeline.

Generated by: polyris init -i
"""
import os
from polyris import DAG, task

STAGE = os.environ.get("POLYRIS_STAGE", "dev")'''
            footer = '''
# Deploy: polyris-deploy --stage $STAGE'''
    
    code = f'''{header}

with DAG(
    dag_id="{name}",
    schedule={schedule_str},
    description="{name} pipeline",
) as dag:

{chr(10).join(task_defs)}

{chr(10).join(dep_lines)}
{footer}
'''
    return code


def interactive_init(name: str, base_dir: str = "."):
    """Interactive pipeline creation wizard."""
    
    print("""
╔══════════════════════════════════════╗
║     polyris pipeline wizard 🧙      ║
╚══════════════════════════════════════╝
""")
    
    # 1. Deploy method
    deploy_method = _ask_choice("How do you want to run this pipeline?", DEPLOY_METHODS)
    
    # 2. Schedule
    schedule = _ask_choice("Schedule:", SCHEDULES)
    
    # 3. Tasks
    print("\n  Define your tasks (press Enter on an empty name to finish):")
    tasks: List[Any] = []
    task_num = 1
    while True:
        # Only the first task carries a suggestion. It used to be
        # {1: extract, 2: transform, 3: load}, which silently contradicted the
        # line above: _ask() returns `result or default`, so Enter accepted the
        # suggestion instead of finishing and no pipeline under three tasks
        # could be built at all. The scaffold is a nudge for an empty wizard,
        # not a floor on task count.
        task_name = _ask(f"Task {task_num} name", default="extract" if not tasks else None)
        if not task_name:
            break
        
        task_info = {"name": task_name}
        
        # Ask for retries (quick)
        retries = _ask(f"  Retries for '{task_name}'", default="0")
        if retries != "0":
            task_info["retries"] = int(retries)
        
        tasks.append(task_info)
        task_num += 1
    
    # 4. Dependencies
    if len(tasks) > 1:
        print("\n  Dependencies (current: sequential chain)")
        print(f"    Chain: {' → '.join(t['name'] for t in tasks)}")
        keep_chain = _ask("  Keep sequential chain? (y/n)", default="y")
        
        if keep_chain.lower() != "y":
            print("  Define dependencies for each task:")
            task_names = [t["name"] for t in tasks]
            for i, t in enumerate(tasks):
                if i == 0:
                    continue
                available = task_names[:i]
                deps = _ask(f"    '{t['name']}' depends on (comma-separated, or 'none')", 
                           default=",".join(available))
                if deps.lower() != "none":
                    t["depends_on"] = [d.strip() for d in deps.split(",") if d.strip() in task_names]
    
    # 5. Generate
    pipeline_dir = Path(base_dir) / name
    if pipeline_dir.exists():
        print(f"\n❌ Directory already exists: {pipeline_dir}")
        sys.exit(1)
    
    pipeline_dir.mkdir(parents=True)
    
    code = _build_custom_pipeline(name, schedule, tasks, deploy_method)
    
    filename = "dag.py"
    (pipeline_dir / filename).write_text(code)
    
    print(f"\n✅ Pipeline created: {pipeline_dir}/{filename}")
    print(f"   Tasks: {' → '.join(t['name'] for t in tasks)}")
    print(f"   Schedule: {schedule}")
    print(f"   Deploy: {deploy_method}")
    
    if deploy_method == "local":
        print(f"""
Try it now:
  cd {pipeline_dir}
  polyris-validate              # Validate pipeline
  polyris-validate -v           # Verbose output
  polyris-output --json         # Full Step Functions JSON
  polyris-output --mermaid      # Generate diagram
  polyris-output --graph        # Show DAG as ASCII graph
""")
    elif deploy_method == "cfn":
        print(f"""
Next steps:
  cd {pipeline_dir}
  polyris-deploy
""")
    else:  # pragma: no cover -- unreachable via the public API: deploy_method
        # comes only from _ask_choice(DEPLOY_METHODS), which yields local|cfn.
        # Kept as a graceful default so adding a third method degrades to a
        # generic next-steps block instead of printing nothing.
        print(f"""
Next steps:
  cd {pipeline_dir}
  polyris-validate
  polyris-deploy
""")


