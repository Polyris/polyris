def init_project(base_dir: str = ".") -> None:
    """Generate config.py template in the project root."""
    config_path = Path(base_dir) / "config.py"

    if config_path.exists():
        print(f"❌ config.py already exists: {config_path}")
        sys.exit(1)

    # Ask for namespace
    namespace = input("  Project namespace (e.g. myorg): ").strip()
    if not namespace:
        namespace = "myorg"

    config_path.write_text(CONFIG_PY_TEMPLATE.format(namespace=namespace))
    print(f"""
✅ Project config created: {config_path}

Next steps:
  1. Edit config.py — set your namespace, region, AWS profiles
  2. Create your first pipeline:
       polyris-init my-pipeline
  3. Deploy infrastructure:
       polyris-deploy --stage dev
""")



def main():
    parser = argparse.ArgumentParser(
        prog="polyris-init",
        description="Create a new polyris pipeline",
        epilog="Examples:\n  polyris-init --project                # Initialize project config.py\n  polyris-init my-pipeline              # Create a pipeline (default)\n  polyris-init my-pipeline --local      # Try without AWS\n  polyris-init my-pipeline --schedule @hourly"
    )
    parser.add_argument("name", nargs="?", default=None, help="Pipeline name (e.g. my-pipeline)")

    deploy_group = parser.add_mutually_exclusive_group()
    deploy_group.add_argument("--cfn", action="store_const", dest="deploy", const="cfn", help="Generate CloudFormation-ready files (default)")
    deploy_group.add_argument("--local", action="store_const", dest="deploy", const="local", help="Try locally without AWS (explore DSL)")

    parser.add_argument("--schedule", default=None, help="Cron schedule (default: @daily)")

    parser.add_argument("--dir", default=".", help="Base directory (default: current directory)")
    parser.add_argument("-i", "--interactive", action="store_true", help="Interactive wizard")
    parser.add_argument("--project", action="store_true", help="Initialize a new polyris project (creates config.py)")

    args = parser.parse_args()

    if args.project:
        init_project(base_dir=args.dir)
        return

    if args.interactive:
        name = args.name
        if not name:
            name = input("  Pipeline name: ").strip()
            if not name:
                print("❌ Pipeline name is required.")
                sys.exit(1)
        interactive_init(name=name, base_dir=args.dir)
    else:
        if not args.name:
            parser.error("Pipeline name is required (or use -i for interactive mode)")
        init_pipeline(
            name=args.name,
            deploy_method=args.deploy or "cfn",
            schedule=args.schedule or "@daily",
            base_dir=args.dir,

        )


if __name__ == "__main__":  # pragma: no cover -- entry-point guard; main() is exercised directly
    main()
