"""Render the console's runtime ``config.js``.

This is the canonical shape of ``window.CONFIG`` (ADR #94: runtime config is
read from ``/config.js`` first). Two writers produce that file:

- this Lambda (``UiBootstrap``), for stacks deployed by ``polyris-up``;
- ``ui/deploy.sh`` (and its twin ``sam/deploy-ui.sh``), for a from-source
  ``sam deploy``.

The shell scripts can't import Python, so their heredocs are pinned to this
renderer by ``tests/backend/test_ui_bootstrap.py`` (parity test, Principle #28).
Change the shape here and that test tells you which scripts to update.
"""
from __future__ import annotations

import json

POLL_INTERVAL_MS = 30000


def render_config_js(*, api_url: str, user_pool_id: str, client_id: str, region: str) -> str:
    """Return the full ``config.js`` text.

    Auth is enabled exactly when a user pool id is present: the template
    passes empty strings for the Cognito ids when ``EnableCognitoAuth`` is
    ``false``.
    """
    auth_enabled = "true" if user_pool_id else "false"
    # json.dumps gives a correctly escaped JS string literal for every value.
    return (
        "// Polyris Console Configuration\n"
        "// Auto-generated by CloudFormation (UiBootstrap) — do not edit manually\n"
        "window.CONFIG = {\n"
        f"    API_URL: {json.dumps(api_url)},\n"
        f"    POLL_INTERVAL: {POLL_INTERVAL_MS},\n"
        "    AUTH: {\n"
        f"        enabled: {auth_enabled},\n"
        f"        userPoolId: {json.dumps(user_pool_id)},\n"
        f"        clientId: {json.dumps(client_id)},\n"
        f"        region: {json.dumps(region)}\n"
        "    }\n"
        "};\n"
    )
